/** Same derivation as the client's demo sign-in, so `<slug>@leadshop.demo` owns each seeded store. */
export function demoUid(email: string) {
  return "demo_" + createHash("sha256").update(email.toLowerCase()).digest("hex").slice(0, 20);
}

export const demoOwnerEmail = (slug: string) => `${slug}@leadshop.demo`;

export function seedStores(): Store[] {
  return stores.map((s) => ({
    ...s,
    ownerUid: demoUid(demoOwnerEmail(s.slug)),
    campusId: C,
    createdAt: now,
    verification: { status: "verified", reviewedAt: now, ...s.verification },
  }));
}

export function seedProducts(): Product[] {
  return products.map(([storeId, name, description, priceNaira, kind, category, emoji, tags, durationMins], i) => ({
    id: `pr_${String(i + 1).padStart(3, "0")}`,
    storeId,
    campusId: C,
    name,
    description,
    priceKobo: priceNaira * 100,
    kind,
    category,
    emoji,
    tags,
    ...(durationMins ? { durationMins } : {}),
    inStock: true,
    createdAt: now,
  }));
}
